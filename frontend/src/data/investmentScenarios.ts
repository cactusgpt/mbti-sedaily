const INITIAL_AMOUNT = 1_000_000;

export function calcInvestment(optionId: string, year: number) {
  const option = INVESTMENT_OPTIONS.find((o) => o.id === optionId)!;
  const multiplier = option.multiplierByYear[year] ?? 1;
  const currentValue = Math.round(INITIAL_AMOUNT * multiplier);
  const returnRate = ((multiplier - 1) * 100);
  return {
    initialAmount: INITIAL_AMOUNT,
    currentValue,
    multiplier,
    returnRate,
    tagline: option.tagline(multiplier),
    story: option.story ? option.story(year, multiplier) : undefined,
  };
}

// 평행우주 시나리오: 선택한 옵션 기준으로 "만약 다른 선택을 했다면" 비교
export function getParallelUniverses(selectedId: string, year: number) {
  return INVESTMENT_OPTIONS
    .filter((o) => o.id !== selectedId)
    .map((o) => {
      const result = calcInvestment(o.id, year);
      return { option: o, result };
    })
    .sort((a, b) => b.result.currentValue - a.result.currentValue);
}
